def comm_type_name(v: int, version: str = "2019") -> str:
    """通信方式名称。version='2013' 时值 3 使用“宽带载波通信”。"""
    if v == 3:
        if version == "2013":
            return "宽带载波通信"
        return "HPLC 载波通信（2013版：宽带载波）"
