def fn_name(afn: int, fn: int) -> str:
    names = AFN_FN_NAMES.get(afn)
    if names and fn in names:
        return names[fn]
    if afn == 0xF0:
        return f"厂家自定义 F{fn}"
    return f"F{fn}"


def dt_to_fns(dt1: int, dt2: int) -> list[tuple[int, int]]:
    """DT1+DT2 → [(Fn, dt1_bit掩码), ...] 按位序（D0→F+1 … D7→F+8）。"""
    base = (dt2 & 0xFF) * 8
    fns = []
    for k in range(8):
        if dt1 & (1 << k):
            fns.append((base + k + 1, 1 << k))
    return fns


