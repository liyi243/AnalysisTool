def main() -> None:
    all_hex = "\n".join(hexs for _, _, hexs in PAIRS)
    result = parse_text(all_hex)
    print(f"输入 {len(PAIRS)} 条报文 → 解析出 {len(result.frames)} 帧\n")
    ok = 0
    for (label, sender, hexs), fr in zip(PAIRS, result.frames):
        cs = "✓" if fr.cs_ok else f"✗({'; '.join(fr.errors)[:40]})"
        valid = "有效" if fr.valid else "无效"
        print(f"[{label}] {sender} len={fr.length} CS={cs} {valid}")
        print(f"    {fr.summary}")
        for e in fr.errors:
            print(f"    ! {e}")
        if fr.valid:
            ok += 1
    print(f"\n通过 {ok}/{len(PAIRS)}")
    # 序列号配对检查
    print("\n=== 报文序列号(R6)配对 ===")
    seqs = []
    for fr in result.frames:
        r6 = None
        for f in fr.fields:
            if f.name == "信息域R":
                r6 = next((c.display_value() for c in f.children
                           if c.name == "报文序列号"), None)
        seqs.append((("↑" if fr.direction.startswith("上行") else "↓"),
                     fr.afn_byte, r6))
    print(seqs)


if __name__ == "__main__":
    main()
